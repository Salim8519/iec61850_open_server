package httpapi

import (
	"net/http"
	"regexp"
	"strings"
)

// waitressBadURI is Waitress' answer when the request target is not ASCII (urlsplit of
// the bytes fails), sent before the application runs.
const waitressBadURI = "Bad Request\r\n\r\nBad URI\r\n\r\n(generated by waitress)"

// rejectBadURI answers like Waitress for a request target with bytes above 0x7f, unless it
// starts with "//" (Waitress then skips urlsplit). It returns true when it answered.
func rejectBadURI(w http.ResponseWriter, r *http.Request) bool {
	uri := r.RequestURI
	if strings.HasPrefix(uri, "//") || isASCII(uri) {
		return false
	}
	w.Header().Set("Connection", "close")
	WriteBody(w, http.StatusBadRequest, "text/plain; charset=utf-8", []byte(waitressBadURI))
	return true
}

// normalizePath is Werkzeug's request.path: "/" plus the path with leading slashes removed.
func normalizePath(r *http.Request) {
	if strings.HasPrefix(r.URL.Path, "//") {
		r.URL.Path = "/" + strings.TrimLeft(r.URL.Path, "/")
		r.URL.RawPath = ""
	}
}

var slashRuns = regexp.MustCompile("/{2,}")

// mergedPath is Werkzeug's merge_slashes retry path, or "" when the path has no "//".
func mergedPath(path string) string {
	if !strings.Contains(path, "//") {
		return ""
	}
	return slashRuns.ReplaceAllString(path, "/")
}

// writeRedirect is Werkzeug's RequestRedirect (308) to the merged path, which Flask returns
// as is (routing redirects skip the error handlers): absolute Location and an HTML page.
func writeRedirect(w http.ResponseWriter, r *http.Request, path string) {
	location := "http://" + requestHost(r) + quotePath(path)
	header := location
	if query := Latin1(r.URL.RawQuery); query != "" {
		location += "?" + query
		// Werkzeug passes the Location header through iri_to_uri.
		header += "?" + percentQuote(query, "%!$&'()*+,/:;=?@")
	}
	escaped := markupEscape.Replace(location)
	body := "<!doctype html>\n<html lang=en>\n<title>Redirecting...</title>\n<h1>Redirecting...</h1>\n" +
		"<p>You should be redirected automatically to the target URL: <a href=\"" + escaped + "\">" +
		escaped + "</a>. If not, click the link.\n"
	w.Header().Set("Location", header)
	WriteBody(w, http.StatusPermanentRedirect, "text/html; charset=utf-8", []byte(body))
}

// markupEscape is markupsafe.escape, which werkzeug.utils.redirect uses for the page.
var markupEscape = strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&#34;", "'", "&#39;")

// quotePath is urllib.parse.quote(path, safe="!$&'()*+,/:;=@").
func quotePath(path string) string { return percentQuote(path, "!$&'()*+,/:;=@") }
