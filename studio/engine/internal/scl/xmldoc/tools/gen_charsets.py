"""Generate the single-byte codec tables pyexpat would build from CPython codecs.

Run with the studio venv Python (CPython 3.12):  python gen_charsets.py
Writes ../charset_tables_a.go, ../charset_tables_b.go and ../charset_names.go.
"""
from pathlib import Path
import encodings.aliases as aliases_module

HERE = Path(__file__).resolve().parent.parent
TABLES = ["cp1250", "cp1251", "cp1252", "cp1253", "cp1254", "cp1255", "cp1256", "cp1257", "cp1258",
          "iso8859_2", "iso8859_3", "iso8859_4", "iso8859_5", "iso8859_7", "iso8859_9", "iso8859_13",
          "iso8859_15", "iso8859_16", "koi8_r", "koi8_u", "cp437", "cp850", "cp852", "mac_roman"]
EIGHT_BIT = ["latin_1", "ascii", "utf_8"]
MULTI = ["utf_16", "utf_16_le", "utf_16_be", "utf_32", "utf_32_le", "utf_32_be", "shift_jis", "euc_jp",
         "euc_kr", "gb2312", "gbk", "gb18030", "big5", "cp932", "cp949", "cp950", "big5hkscs", "iso2022_jp",
         "iso2022_kr", "hz", "johab", "shift_jisx0213", "euc_jis_2004", "utf_7", "cp936"]
HEADER = ["package xmldoc", "", "// Code generated by tools/gen_charsets.py from CPython 3.12 codecs; DO NOT EDIT.", ""]


def table_lines(names, variable):
    out = HEADER + [f"var {variable} = map[string]*[128]uint16{{"]
    for name in names:
        row = []
        for byte in range(128, 256):
            char = bytes([byte]).decode(name, "replace")
            row.append(0 if char == "�" else ord(char))
        for byte in range(128):
            assert bytes([byte]).decode(name) == chr(byte), (name, byte)
        out.append(f'\t"{name}": {{')
        for index in range(0, 128, 16):
            out.append("\t\t" + ", ".join(f"0x{value:04x}" for value in row[index:index + 16]) + ",")
        out.append("\t},")
    return out + ["}"]


def name_lines():
    known = set(TABLES) | set(EIGHT_BIT)
    aliases = {alias: target for alias, target in aliases_module.aliases.items() if target in known}
    aliases.update({name: name for name in known})
    multi = {alias for alias, target in aliases_module.aliases.items() if target in MULTI} | set(MULTI)
    out = HEADER + ["// pythonAliases maps normalised Python codec names to the codecs tabled here.",
                    "var pythonAliases = map[string]string{"]
    out += [f'\t"{key}": "{aliases[key]}",' for key in sorted(aliases)]
    out += ["}", "", "// multiByteCodecs are Python codecs pyexpat refuses as multi-byte.",
            "var multiByteCodecs = map[string]bool{"]
    out += [f'\t"{key}": true,' for key in sorted(multi)]
    return out + ["}"]


def write(name, lines):
    (HERE / name).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    assert len(lines) < 299, (name, len(lines))


write("charset_tables_a.go", table_lines(TABLES[:12], "singleByteTablesA"))
write("charset_tables_b.go", table_lines(TABLES[12:], "singleByteTablesB"))
write("charset_names.go", name_lines())
