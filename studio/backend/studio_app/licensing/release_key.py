"""Release constants: accepted Ed25519 public keys and the default license server.

Generated by studio/tools/configure_release.py; edit through that tool so the
Python and native copies always match. Keys are stored XOR-masked only so they do
not appear as a plain searchable hex string; they are public, not secret.
"""
import hashlib

DEFAULT_SERVER_URL = "https://license.scadabench.com"
_MASK = bytes.fromhex("5d1fa7c3398e04b26af10c947e23d8a1")
_MASKED_KEYS = [
    "1d13befc03e02574daee137734f229016c9b29de7aa60b0af8daa2a515ec395b",
]


def _unmask(masked):
    return bytes(value ^ _MASK[index % len(_MASK)] for index, value in enumerate(bytes.fromhex(masked)))


def key_id(public_key):
    """Short identifier carried in each certificate as "kid"."""
    return hashlib.sha256(public_key).hexdigest()[:8]


def public_keys():
    """Return {kid: public_key} for every key this release accepts."""
    keys = (_unmask(masked) for masked in _MASKED_KEYS)
    return {key_id(key): key for key in keys}


def configured():
    return bool(_MASKED_KEYS) and bool(DEFAULT_SERVER_URL)
