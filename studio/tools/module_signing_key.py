"""Create the module-integrity signing key, once per release line.

    python studio/tools/module_signing_key.py            create if absent, else show
    python studio/tools/module_signing_key.py --force    replace (invalidates old .sig)

Writes the SECRET seed to studio/native/release/module_signing.seed (git-ignored) and
the PUBLIC key into studio/native/release/module_key.hpp (committed, masked only to
avoid a plain hex search). The build signs the compiled module with the seed; the
native workers verify it with the public key. This key is separate from the license
key so the build stays self-contained (no license-server round trip).
"""
import argparse
import secrets
import sys
from pathlib import Path

STUDIO = Path(__file__).resolve().parents[1]
RELEASE = STUDIO / "native/release"
SEED_FILE = RELEASE / "module_signing.seed"
HEADER_FILE = RELEASE / "module_key.hpp"
MASK = bytes.fromhex("5d1fa7c3398e04b26af10c947e23d8a1")
sys.path.insert(0, str(STUDIO / "backend"))


def _mask(key):
    return bytes(value ^ MASK[index % len(MASK)] for index, value in enumerate(key))


def native_header(public_key):
    masked = _mask(public_key)
    row = ", ".join(f"0x{byte:02x}" for byte in masked)
    mask_bytes = ", ".join(f"0x{byte:02x}" for byte in MASK)
    return f"""// Generated by studio/tools/module_signing_key.py. The 32-byte Ed25519 public key
// that native workers use to verify the shipped compiled module. Public, masked only
// to avoid a plain-text search; the matching secret seed never leaves the build host.
#pragma once
#include <array>
#include <cstdint>

namespace module_key {{

constexpr std::array<std::uint8_t, 16> kMask = {{
    {mask_bytes}}};
constexpr std::size_t kKeyCount = 1;
constexpr std::array<std::array<std::uint8_t, 32>, (kKeyCount ? kKeyCount : 1)> kMaskedKeys = {{{{
    {{{row}}}
}}}};

}}  // namespace module_key
"""


def write_key(seed):
    from studio_app.licensing.ed25519_sign import public_key
    public = public_key(seed)
    RELEASE.mkdir(parents=True, exist_ok=True)
    SEED_FILE.write_text(seed.hex(), encoding="utf-8", newline="\n")
    HEADER_FILE.write_text(native_header(public), encoding="utf-8", newline="\n")
    return public


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="replace the existing key (old signatures stop verifying)")
    args = parser.parse_args(argv)
    if SEED_FILE.exists() and not args.force:
        seed = bytes.fromhex(SEED_FILE.read_text(encoding="utf-8").strip())
        from studio_app.licensing.ed25519_sign import public_key
        print(f"Module key present. Public key: {public_key(seed).hex()}")
        if not HEADER_FILE.exists():
            write_key(seed)
            print(f"Regenerated {HEADER_FILE}")
        return 0
    public = write_key(secrets.token_bytes(32))
    print(f"Module signing key created. Public key: {public.hex()}")
    print(f"Secret seed: {SEED_FILE} (keep private; git-ignored). Header: {HEADER_FILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
