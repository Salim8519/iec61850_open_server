"""Set the release license server address and Ed25519 public key(s) in one step.

Interactive (press Enter to keep the [current] value):
    python studio/tools/configure_release.py
Non-interactive (the license server's `configure` prints this line for you):
    python studio/tools/configure_release.py --server-url https://license.example.com --public-key <64 hex>
Rewrites, together and always in sync:
    studio/backend/studio_app/licensing/release_key.py   (Python backend)
    studio/native/release/release_key.hpp                 (native workers)
"""
import argparse
import hashlib
from pathlib import Path
import re
import sys

STUDIO = Path(__file__).resolve().parents[1]
PYTHON_FILE = STUDIO / "backend/studio_app/licensing/release_key.py"
NATIVE_FILE = STUDIO / "native/release/release_key.hpp"
MASK = bytes.fromhex("5d1fa7c3398e04b26af10c947e23d8a1")
sys.path.insert(0, str(STUDIO / "backend"))


def mask(key):
    return bytes(value ^ MASK[index % len(MASK)] for index, value in enumerate(key))


def current_values(python_file=PYTHON_FILE):
    text = python_file.read_text(encoding="utf-8")
    url = re.search(r'^DEFAULT_SERVER_URL = "([^"]*)"', text, re.MULTILINE).group(1)
    masked = re.findall(r'"([0-9a-f]{64})"', text.split("_MASKED_KEYS", 1)[1])
    return url, [mask(bytes.fromhex(item)).hex() for item in masked]


def validate_key(text):
    from studio_app.licensing import ed25519_verify
    value = text.strip().lower()
    if not re.fullmatch(r"[0-9a-f]{64}", value):
        raise SystemExit(f"Public key must be 64 hex characters (got {len(value)}): {text!r}")
    if ed25519_verify._decompress(bytes.fromhex(value)) is None:
        raise SystemExit("That is not a valid Ed25519 public key. Copy it again from `license-server status`.")
    return value


def validate_url(text):
    value = text.strip().rstrip("/")
    if not value.startswith("https://"):
        raise SystemExit("The server URL must start with https:// (Cloudflare Tunnel gives you one).")
    return value


def python_source(url, keys):
    masked = "".join(f'    "{mask(bytes.fromhex(key)).hex()}",\n' for key in keys)
    template = PYTHON_FILE.read_text(encoding="utf-8")
    head = template.split("DEFAULT_SERVER_URL", 1)[0]
    tail = template.split("\n\n\ndef _unmask", 1)[1]
    keys_block = f"_MASKED_KEYS = [\n{masked}]" if keys else "_MASKED_KEYS = []"
    return (f'{head}DEFAULT_SERVER_URL = "{url}"\n_MASK = bytes.fromhex("{MASK.hex()}")\n'
            f"{keys_block}\n\n\ndef _unmask{tail}")


def native_source(keys):
    rows = []
    for key in keys:
        masked = mask(bytes.fromhex(key))
        rows.append("    {{" + ", ".join(f"0x{byte:02x}" for byte in masked) + "}}")
    body = ",\n".join(rows) if rows else "    {{}}"
    mask_bytes = ", ".join(f"0x{byte:02x}" for byte in MASK)
    return f"""// Generated by studio/tools/configure_release.py; keep identical to
// studio_app/licensing/release_key.py. Keys are public; masking only hides them
// from plain-text searches.
#pragma once
#include <array>
#include <cstdint>

namespace release_key {{

constexpr std::array<std::uint8_t, 16> kMask = {{
    {mask_bytes}}};

// Each entry is one accepted 32-byte Ed25519 public key, XOR-masked with kMask.
constexpr std::size_t kKeyCount = {len(keys)};
constexpr std::array<std::array<std::uint8_t, 32>, (kKeyCount ? kKeyCount : 1)> kMaskedKeys = {{{{
{body}
}}}};

}}  // namespace release_key
"""


def ask(question, current):
    answer = input(f"{question} [{current or 'not set'}]: ").strip()
    return answer or current


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--server-url")
    parser.add_argument("--public-key", action="append",
                        help="accepted key (repeat to accept several, e.g. during key rotation)")
    parser.add_argument("--add-key", action="store_true", help="keep existing keys and add --public-key")
    parser.add_argument("--native-out", type=Path, help="write the native header elsewhere (test builds)")
    parser.add_argument("--show", action="store_true", help="print the current values and exit")
    args = parser.parse_args(argv)
    url, keys = current_values()
    if args.show:
        print(f"Server URL: {url or 'not set'}")
        for key in keys:
            print(f"Public key: {key}  (kid {hashlib.sha256(bytes.fromhex(key)).hexdigest()[:8]})")
        return 0
    if args.server_url is None and args.public_key is None:
        url = validate_url(ask("License server URL", url))
        keys = [validate_key(ask("Ed25519 public key (64 hex)", keys[0] if keys else ""))]
    else:
        url = validate_url(args.server_url) if args.server_url is not None else url
        if args.public_key:
            fresh = [validate_key(item) for value in args.public_key for item in value.split(",") if item.strip()]
            keys = list(dict.fromkeys((keys if args.add_key else []) + fresh))
    if not url or not keys:
        raise SystemExit("Both a server URL and at least one public key are required.")
    if args.native_out:
        args.native_out.mkdir(parents=True, exist_ok=True)
        (args.native_out / "release_key.hpp").write_text(native_source(keys), encoding="utf-8")
        print(f"Native header written to {args.native_out}")
        return 0
    PYTHON_FILE.write_text(python_source(url, keys), encoding="utf-8")
    NATIVE_FILE.write_text(native_source(keys), encoding="utf-8")
    print(f"Release configured: {url}, {len(keys)} key(s). Rebuild with compile_protected.py when ready.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
